// 获取当前语言的文本
function t(key, lang = localStorage.getItem('language') || 'zh') {
  const keys = key.split('.');
  let value = i18n[lang];
  
  for (const k of keys) {
    if (value && value[k] !== undefined) {
      value = value[k];
    } else {
      return key; // 如果找不到键，返回原始键
    }
  }
  
  return value;
}

// 切换语言并更新页面
function switchLanguage(lang) {
  // 写入本地缓存
  localStorage.setItem('language', lang);
  // 更新页面文本
  updatePageText();
  // 显示提示
  alert(t('alerts.languageSwitched', lang));
  // 调用API更新语言设置（确保函数已定义）
  if (typeof updateLanguageSettings === 'function') {
    updateLanguageSettings(lang);
  }
}

